WITH TRIPS AS (
    SELECT
    RIDE_ID,
    RIDEABLE_TYPE, 
    DATE(TO_TIMESTAMP(STARTED_AT))AS STARTED_AT,
    START_STATIO_ID AS START_STATION_ID,
    MEMBER_CSUAL AS MEMBER_CASUAL,
    TIMESTAMPDIFF(SECOND,TO_TIMESTAMP(STARTED_AT), TO_TIMESTAMP(ENDED_AT))
    FROM 
    {{source('demo','BIKE')}}
    WHERE RIDE_ID != 'ride_id'
)

SELECT 
*
FROM TRIPS